const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('../../supabase/tests/rpc-authorization/node_modules/@electric-sql/pglite');
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const loc = n => `https://project.supabase.co/storage/v1/object/public/chat-media/${id(n)}/photo.jpg`;

test('actual migration closes private-media forgery, limited-view and group-call authorization paths', async () => {
 const db = new PGlite();
 try {
 await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 CREATE FUNCTION public.can_act_as(p uuid) RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT coalesce(p=auth.uid(),false) $$;
 CREATE TABLE conversations(id uuid PRIMARY KEY,is_group boolean,user_1 uuid,user_2 uuid);
 CREATE TABLE conversation_members(conversation_id uuid,user_id uuid,PRIMARY KEY(conversation_id,user_id));
 CREATE FUNCTION public.is_conversation_member(c uuid,u uuid) RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT EXISTS(SELECT 1 FROM conversation_members WHERE conversation_id=c AND user_id=u) $$;
 CREATE TABLE messages(id uuid PRIMARY KEY,sender_id uuid,receiver_id uuid,conversation_id uuid,media_url text,thumbnail_url text,media_type text,view_limit smallint,forwarded_from_id uuid,deleted_at timestamptz);
 CREATE TABLE message_views(message_id uuid,user_id uuid,views integer,first_viewed_at timestamptz,PRIMARY KEY(message_id,user_id));
 CREATE TABLE call_sessions(id uuid PRIMARY KEY,conversation_id uuid,initiator_id uuid,receiver_id uuid,is_group_call boolean,status text,created_at timestamptz DEFAULT now(),expires_at timestamptz,started_at timestamptz,ended_at timestamptz,duration_sec integer);
 CREATE TABLE call_participants(call_session_id uuid,user_id uuid,status text,joined_at timestamptz,left_at timestamptz,last_seen_at timestamptz,PRIMARY KEY(call_session_id,user_id));
 INSERT INTO conversations VALUES('${id(10)}',false,'${id(1)}','${id(2)}'),('${id(11)}',false,'${id(2)}','${id(3)}'),('${id(12)}',true,'${id(1)}',null);
 INSERT INTO conversation_members VALUES('${id(12)}','${id(1)}'),('${id(12)}','${id(2)}');`);
 await db.exec(fs.readFileSync(path.join(__dirname,'../../supabase/migrations/20261022211236_message_call_access.sql'),'utf8'));
 const as = user => db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[id(user)]);
 const value = async (sql, args=[]) => (await db.query(sql,args)).rows[0];
 await as(1);
 await db.query(`INSERT INTO messages(id,sender_id,conversation_id,media_url,media_type) VALUES($1,$2,$3,$4,'image')`,[id(20),id(1),id(10),loc(1)]);
 await as(2);
 assert.equal((await db.query('SELECT * FROM chat_media_manifest($1)',[[id(20)]])).rows.length,1);
 assert.equal((await value('SELECT can_read_chat_object($1,$2) ok',['chat-media',`${id(1)}/photo.jpg`])).ok,true);
 await db.query(`INSERT INTO messages(id,sender_id,conversation_id,media_url,media_type,forwarded_from_id) VALUES($1,$2,$3,$4,'image',$5)`,[id(21),id(2),id(11),loc(1),id(20)]);
 await as(3);
 assert.equal((await db.query('SELECT * FROM chat_media_manifest($1)',[[id(20)]])).rows.length,0);
 assert.equal((await db.query('SELECT * FROM chat_media_manifest($1)',[[id(21)]])).rows.length,1);
 await assert.rejects(db.query(`INSERT INTO messages(id,sender_id,conversation_id,media_url,media_type) VALUES($1,$2,$3,$4,'image')`,[id(22),id(3),id(11),loc(1)]),/not authorized/);
 await assert.rejects(db.query(`UPDATE messages SET media_url=$1 WHERE id=$2`,[loc(3),id(21)]),/immutable/);
 await as(1);
 await db.query(`INSERT INTO messages(id,sender_id,conversation_id,media_url,media_type,view_limit) VALUES($1,$2,$3,$4,'image',1)`,[id(23),id(1),id(10),loc(1).replace('photo','sealed')]);
 await as(2);
 assert.equal((await value('SELECT can_read_chat_object($1,$2) ok',['chat-media',`${id(1)}/sealed.jpg`])).ok,false);
 let grant = await value('SELECT * FROM claim_chat_media_view($1,$2)',[id(23),id(30)]);
 assert.ok(grant.url); assert.equal(grant.remaining,0);
 assert.equal((await value('SELECT * FROM claim_chat_media_view($1,$2)',[id(23),id(30)])).url,grant.url);
 assert.equal((await value('SELECT * FROM claim_chat_media_view($1,$2)',[id(23),id(31)])).url,null);
 await assert.rejects(db.query('SELECT * FROM consume_media_view($1)',[id(23)]),/Update Platinum/);
 await db.query(`UPDATE messages SET deleted_at=now() WHERE id=$1`,[id(23)]);
 assert.equal((await value('SELECT * FROM claim_chat_media_view($1,$2)',[id(23),id(30)])).url,null);
 await db.exec(`ALTER TABLE call_sessions DISABLE TRIGGER call_session_lifecycle_guard; INSERT INTO call_sessions(id,conversation_id,initiator_id,is_group_call,status,expires_at) VALUES('${id(40)}','${id(12)}','${id(1)}',true,'ringing',now()-interval '1 second'),('${id(41)}','${id(12)}','${id(1)}',true,'ringing',now()+interval '1 minute');
 INSERT INTO call_participants(call_session_id,user_id,status) VALUES('${id(41)}','${id(1)}','joined'),('${id(41)}','${id(2)}','invited'); ALTER TABLE call_sessions ENABLE TRIGGER call_session_lifecycle_guard;`);
 await assert.rejects(db.query('SELECT join_group_call($1)',[id(40)]),/no longer available/);
 await as(3);
 await assert.rejects(db.query('SELECT leave_group_call($1)',[id(41)]),/Not a participant/);
 await assert.rejects(db.query('SELECT decline_group_call($1)',[id(41)]),/Not a participant/);
 await assert.rejects(db.query('SELECT join_group_call($1)',[id(41)]),/Not a member/);
 await as(2);
 await db.query('SELECT join_group_call($1)',[id(41)]);
 assert.equal((await value('SELECT status FROM call_sessions WHERE id=$1',[id(41)])).status,'active');
 const oldIdentity = (await value('SELECT provider_identity FROM call_participants WHERE call_session_id=$1 AND user_id=$2',[id(41),id(2)])).provider_identity;
 await db.query('SELECT leave_group_call($1)',[id(41)]);
 assert.equal((await value('SELECT count(*)::int n FROM call_provider_revocations')).n,1);
 await db.query('SELECT join_group_call($1)',[id(41)]);
 assert.notEqual((await value('SELECT provider_identity FROM call_participants WHERE call_session_id=$1 AND user_id=$2',[id(41),id(2)])).provider_identity,oldIdentity);
 await db.query('DELETE FROM conversation_members WHERE conversation_id=$1 AND user_id=$2',[id(12),id(2)]);
 assert.equal((await value('SELECT status FROM call_participants WHERE call_session_id=$1 AND user_id=$2',[id(41),id(2)])).status,'left');
 assert.equal((await value('SELECT count(*)::int n FROM call_provider_revocations')).n,2);
 await assert.rejects(db.query('SELECT join_group_call($1)',[id(41)]),/Not a member/);
 assert.equal((await db.query('SELECT * FROM claim_call_revocations(50)')).rows.length,2);
 assert.equal((await db.query('SELECT * FROM claim_call_revocations(50)')).rows.length,0);
 } finally { await db.close(); }
});
