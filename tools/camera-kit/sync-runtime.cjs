const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const engineDir = path.join(root, 'src/screens/stories');
const target = path.join(engineDir, 'cameraKitEngine.ts');
const readLiteral = source => JSON.parse(source.slice(source.indexOf(' = ') + 3).trim().replace(/;$/, ''));
function readEngineHtml() {
  const source = fs.readFileSync(target, 'utf8');
  if (source.includes('CAMERA_KIT_ENGINE_HTML: string = "')) return readLiteral(source);
  const imports = [...source.matchAll(/from '\.\/(cameraKitEnginePart\d+)'/g)];
  if (!imports.length) throw new Error('Camera Kit chunk imports are missing.');
  return imports.map(match => readLiteral(fs.readFileSync(path.join(engineDir, match[1] + '.ts'), 'utf8'))).join('');
}
function generatedFiles(html) {
  const files = new Map(), names = []; let offset = 0;
  while (offset < html.length) {
    let length = Math.min(220000, html.length - offset), content;
    const index = names.length + 1, name = `CAMERA_KIT_ENGINE_PART_${index}`;
    do {
      content = '// Generated by tools/camera-kit/sync-runtime.cjs; do not edit.\nexport const ' + name + ': string = ' + JSON.stringify(html.slice(offset, offset + length)) + ';\n';
      if (Buffer.byteLength(content, 'utf8') <= 280000) break;
      length = Math.floor(length * .8);
    } while (length > 0);
    if (!length) throw new Error('Unable to encode Camera Kit HTML chunk.');
    names.push(name); files.set(`cameraKitEnginePart${index}.ts`, content); offset += length;
  }
  files.set('cameraKitEngine.ts', '// Bundled @snap/camera-kit 1.20.0. SDK bytes are unchanged.\n// Custom source: tools/camera-kit/runtime.js; refresh with node tools/camera-kit/sync-runtime.cjs\n' + names.map((name,index) => `import { ${name} } from './cameraKitEnginePart${index+1}';`).join('\n') + '\nexport const CAMERA_KIT_ENGINE_HTML: string = ' + names.join(' + ') + ';\n');
  return files;
}
function syncRuntime() {
  const html = readEngineHtml(), marker = '/* PLATINUM_CAMERA_RUNTIME_START */';
  const start = html.includes(marker) ? html.indexOf(marker) : html.indexOf('var XI=document.getElementById("live")');
  const end = html.lastIndexOf('})();');
  if (start < 0 || end < start) throw new Error('Camera Kit bundle markers changed. Regenerate with the SDK before replacing the runtime.');
  const runtime = fs.readFileSync(path.join(__dirname, 'runtime.js'), 'utf8');
  const updated = html.slice(0, start) + marker + '\n' + runtime + '\n/* PLATINUM_CAMERA_RUNTIME_END */' + html.slice(end);
  const files = generatedFiles(updated);
  for (const [name, contents] of files) fs.writeFileSync(path.join(engineDir, name), contents);
  for (const name of fs.readdirSync(engineDir)) if (/^cameraKitEnginePart\d+\.ts$/.test(name) && !files.has(name)) fs.unlinkSync(path.join(engineDir, name));
}
if (require.main === module) syncRuntime();
module.exports = { readEngineHtml, generatedFiles };
