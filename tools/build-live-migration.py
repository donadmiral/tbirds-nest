"""Regenerate the portable migration from recovered, immutable QA source."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'supabase/reference/live-qa-recovered'
TARGET = ROOT / 'supabase/migrations/20261103000609_live_portable_control_plane.sql'

def strip_transaction(text):
    text = re.sub(r'^begin;\n', '', text, count=1, flags=re.M)
    return re.sub(r'\ncommit;\s*$', '\n', text)

def definition(text, name):
    match = re.search(r'create function live_streams\.' + re.escape(name) + r'\([\s\S]*?\$\$;', text)
    if not match:
        raise ValueError(name)
    return match.group(0)

core = strip_transaction((SOURCE / '20261102201821_live_streams_control_plane.sql').read_text())
# Gifts remain unavailable. Do not require an unrelated QA-only payments schema.
core = core.replace('order_id uuid primary key references creator_finance.orders(id)', 'order_id uuid primary key')
gift_query = " select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'title',p.title,'amount_minor',p.amount_minor::text,'currency',p.currency) order by p.created_at,p.id),'[]') into gifts\n from (select * from creator_finance.products where creator_id=s.host_id and kind='gift' and active order by created_at,id limit 30) p;"
assert core.count(gift_query) == 1
core = core.replace(gift_query, " -- Paid gifts are deliberately deferred; no catalog or checkout is exposed.")
identity = (ROOT / 'supabase/reference/live-portable-identity.sql').read_text()
for name in ['active_user', 'publisher_allowed', 'require_user']:
    core = core.replace(definition(core, name), '')
anchor = 'create function live_streams.require_publisher('
assert core.count(anchor) == 1
core = core.replace(anchor, identity + '\n' + anchor)
for actor in ['s.host_id', 'm.user_id']:
    old = "and not exists(select 1 from admin_ops.staff_social_shells where user_id=" + actor + ")\n"
    old += ("    " if actor == 'm.user_id' else " ") + "and not exists(select 1 from account_erasure.jobs where user_id=" + actor + " and state<>'completed')"
    assert core.count(old) == 1, actor
    core = core.replace(old, 'and live_streams.account_available(' + actor + ')')

cover = strip_transaction((SOURCE / '20261102202217_live_cover_lifecycle.sql').read_text())
cover = cover.replace('perform account_erasure.assert_writable(asset.user_id);', """if not live_streams.account_available(asset.user_id) then raise exception 'LIVE_COVER_UPLOAD_NOT_AUTHORIZED' using errcode='42501';end if;
 if to_regprocedure('account_erasure.assert_writable(uuid)') is not null then
  execute 'select account_erasure.assert_writable($1)' using asset.user_id;
 end if;""")
cover = cover.replace("source:=pg_get_functiondef('account_erasure.review_reason(uuid)'::regprocedure);", """if to_regprocedure('account_erasure.review_reason(uuid)') is null then return;end if;
 source:=pg_get_functiondef('account_erasure.review_reason(uuid)'::regprocedure);""")
worker = strip_transaction((SOURCE / '20261102211818_live_worker_schedule.sql').read_text())

out = """-- Generated by tools/build-live-migration.py from the inspected QA source.
-- Additive Live installation on production; forward-compatible with existing QA.
-- All broadcasting, recording, delivery and reminder gates retain their values.
begin;
set local lock_timeout='3s';
set local statement_timeout='60s';
do $install$ begin
 if to_regnamespace('live_streams') is null then
  execute $live_core$
""" + core + """
$live_core$;
 elsif to_regclass('live_streams.settings') is null
  or to_regprocedure('live_streams.service_context(uuid,uuid,uuid,text,uuid)') is null then
  raise exception 'LIVE_EXISTING_SCHEMA_NOT_RECOGNIZED';
 end if;
end $install$;
""" + identity + '\n'
for name in ['can_view', 'service_context', 'detail']:
    out += definition(core, name).replace('create function ', 'create or replace function ', 1) + '\n'
out += "do $cover_install$ begin if to_regclass('live_streams.cover_cleanup') is null then execute $live_cover$\n" + cover + "\n$live_cover$;end if;end $cover_install$;\n"
out += definition(cover, 'bind_cover_owner').replace('create function ', 'create or replace function ', 1) + '\n'
out += "revoke all on function live_streams.bind_cover_owner() from public,anon,authenticated,service_role;\n"
out += "do $worker_install$ begin if to_regclass('live_streams.worker_settings') is null then execute $live_worker$\n" + worker + "\n$live_worker$;end if;end $worker_install$;\n"
out += "notify pgrst,'reload schema';\ncommit;\n"
TARGET.write_text(out)
print(f'Generated {TARGET.name}: {len(out)} bytes')
